#!/usr/bin/env bash
# Benchmarks Go BLAKE3 libraries and the BLAKE3 C library (via cgo) against Go's
# SHA-256, single-threaded, and writes a Markdown report.
#
# Usage: run.sh [report.md] [count]
# Needs Go >= 1.22, a C compiler and python3. Go modules are vendored.
set -euo pipefail
cd "$(dirname "$0")"
here=$PWD
out=${1:-$here/results-$(uname -s | tr A-Z a-z)-$(uname -m).md}
count=${2:-10}
work=$(mktemp -d)
cc=${CC:-cc}

# Builds libblake3.a into $1 with the remaining arguments as extra C flags.
build() {
  local dir=$1
  shift
  mkdir -p "$dir"
  for f in blake3 blake3_dispatch blake3_portable; do
    "$cc" -O3 "$@" -c "c/$f.c" -o "$dir/$f.o"
  done
  case "$(uname -m)" in
    x86_64 | amd64)
      "$cc" -O3 "$@" -msse2 -c c/blake3_sse2.c -o "$dir/sse2.o"
      "$cc" -O3 "$@" -msse4.1 -c c/blake3_sse41.c -o "$dir/sse41.o"
      "$cc" -O3 "$@" -mavx2 -c c/blake3_avx2.c -o "$dir/avx2.o"
      if [[ " $* " != *" -DBLAKE3_NO_AVX512 "* ]]; then
        "$cc" -O3 "$@" -mavx512f -mavx512vl -c c/blake3_avx512.c -o "$dir/avx512.o"
      fi
      ;;
    aarch64 | arm64)
      "$cc" -O3 "$@" -c c/blake3_neon.c -o "$dir/neon.o"
      ;;
  esac
  ar rcs "$dir/libblake3.a" "$dir"/*.o
}

# Runs the benchmarks matching $2 against the library in $work/$1.
bench() {
  local lib=$1 filter=$2
  CGO_CFLAGS="-I$here/c" CGO_LDFLAGS="-L$work/$lib" GOFLAGS=-mod=vendor GOMAXPROCS=1 \
    go test -run TestAgree -count 1 .
  CGO_CFLAGS="-I$here/c" CGO_LDFLAGS="-L$work/$lib" GOFLAGS=-mod=vendor GOMAXPROCS=1 \
    go test -run '^$' -bench "$filter" -count "$count" -benchtime 0.5s . | tee "$work/$lib.txt"
}

case "$(uname -m)" in
  x86_64 | amd64)
    build "$work/default"
    build "$work/noavx512" -DBLAKE3_NO_AVX512
    bench default .
    bench noavx512 'Hash/c/'
    ;;
  *)
    build "$work/default"
    bench default .
    touch "$work/noavx512.txt"
    ;;
esac

{
  echo "# Go vs. C BLAKE3, single thread"
  echo
  echo "Generated by scratch/gob3/run.sh on $(date -u +%Y-%m-%dT%H:%MZ)."
  echo
  echo '```'
  uname -srm
  (lscpu 2>/dev/null | grep -E '^(Model name|CPU\(s\)|Thread|Core|Socket|L[123])' || sysctl -n machdep.cpu.brand_string) | sed 's/  */ /g'
  echo "flags: $(grep -m1 -o -w -E 'avx2|avx512f|avx512vl|sha_ni|vaes' /proc/cpuinfo 2>/dev/null | sort -u | tr '\n' ' ')"
  go version
  "$cc" --version | head -1
  echo '```'
  echo
  python3 - "$work/default.txt" "$work/noavx512.txt" <<'EOF'
import collections, re, statistics, sys

rows = {
    "sha256": "Go crypto/sha256, 32 KiB writes",
    "zeebo": "zeebo/blake3 v0.2.3 (BuildBuddy), 32 KiB writes",
    "luke": "lukechampine.com/blake3 v1.4.1, 32 KiB writes",
    "c": "C BLAKE3, one call",
    "c32k": "C BLAKE3, 32 KiB writes via cgo",
    "c-noavx512": "C BLAKE3 without AVX-512, one call",
}
r = collections.defaultdict(list)
for path, suffix in ((sys.argv[1], ""), (sys.argv[2], "-noavx512")):
    for line in open(path):
        m = re.match(r"BenchmarkHash/(\w+)/(\d+)(?:-\d+)?\s+\d+\s+[\d.]+ ns/op\s+([\d.]+) MB/s", line)
        if m:
            r[(m[1] + suffix, int(m[2]))].append(float(m[3]))
sizes = sorted({k[1] for k in r})
print("Median GB/s of %d runs, GOMAXPROCS=1.\n" % len(next(iter(r.values()))))
print("| | " + " | ".join(f"{s // 1024} KiB" if s < 1 << 20 else f"{s >> 20} MiB" for s in sizes) + " |")
print("|---" * (len(sizes) + 1) + "|")
for key, label in rows.items():
    if (key, sizes[0]) in r:
        print(f"| {label} | " + " | ".join(f"{statistics.median(r[(key, s)]) / 1000:.2f}" for s in sizes) + " |")
EOF
  echo
  echo "<details><summary>Raw output</summary>"
  echo
  echo '```'
  cat "$work/default.txt" "$work/noavx512.txt"
  echo '```'
  echo "</details>"
} > "$out"
echo "Wrote $out"
