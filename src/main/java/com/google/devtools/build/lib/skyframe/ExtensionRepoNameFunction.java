package com.google.devtools.build.lib.skyframe;

import com.google.devtools.build.lib.bazel.bzlmod.BazelDepGraphValue;
import com.google.devtools.build.lib.bazel.bzlmod.ModuleExtensionId;
import com.google.devtools.build.lib.bazel.bzlmod.SingleExtensionValue;
import com.google.devtools.build.lib.cmdline.ExtensionRepositoryMapping;
import com.google.devtools.build.lib.cmdline.RepositoryMapping;
import com.google.devtools.build.lib.cmdline.RepositoryName;
import com.google.devtools.build.skyframe.SkyFunction;
import com.google.devtools.build.skyframe.SkyKey;
import com.google.devtools.build.skyframe.SkyValue;
import java.util.Map;
import javax.annotation.Nullable;
import net.starlark.java.spelling.SpellChecker;

/** {@link SkyFunction} for {@link ExtensionRepoNameValue}s. */
public final class ExtensionRepoNameFunction implements SkyFunction {

  @Nullable
  @Override
  public SkyValue compute(SkyKey skyKey, Environment env) throws InterruptedException {
    var key = (ExtensionRepoNameValue.Key) skyKey;
    var bazelDepGraphValue = (BazelDepGraphValue) env.getValue(BazelDepGraphValue.KEY);
    if (bazelDepGraphValue == null) {
      return null;
    }
    ModuleExtensionId extensionId = null;
    for (Map.Entry<ModuleExtensionId, String> entry :
        bazelDepGraphValue.getExtensionUniqueNames().entrySet()) {
      if (key.repoPrefix().equals(entry.getValue() + "+")) {
        extensionId = entry.getKey();
        break;
      }
    }
    if (extensionId == null) {
      // The extension no longer exists, so neither does the repo.
      return new ExtensionRepoNameValue.Missing("");
    }
    var extensionValue = (SingleExtensionValue) env.getValue(SingleExtensionValue.key(extensionId));
    if (extensionValue == null) {
      return null;
    }
    if (extensionValue.generatedRepoSpecs().containsKey(key.internalName())) {
      return ExtensionRepoNameValue.EXISTS;
    }

    // Only compute suggestions in the error case. Base them on the apparent names that a mapping
    // listing all repos generated by the extension would contain.
    RepositoryName hostRepo = extensionId.bzlFileLabel().getRepository();
    var hostMappingValue =
        (RepositoryMappingValue) env.getValue(RepositoryMappingValue.key(hostRepo));
    if (hostMappingValue == null) {
      return null;
    }
    if (!(hostMappingValue.repositoryMapping() instanceof RepositoryMapping.Explicit hostMapping)) {
      // The extension isn't defined in a Bazel module, which RepositoryMappingFunction reports.
      return new ExtensionRepoNameValue.Missing("");
    }
    var explicitMapping =
        ExtensionRepositoryMapping.createExplicit(
            hostRepo,
            key.repoPrefix(),
            hostMapping,
            bazelDepGraphValue.getRepoOverrides().row(extensionId),
            extensionValue.generatedRepoSpecs().keySet());
    return new ExtensionRepoNameValue.Missing(
        SpellChecker.didYouMean(key.internalName(), explicitMapping.entries().keySet()));
  }
}
