package com.google.devtools.build.lib.skyframe;

import static com.google.common.base.Preconditions.checkNotNull;

import com.google.devtools.build.lib.cmdline.ExtensionRepositoryMapping;
import com.google.devtools.build.lib.skyframe.serialization.autocodec.AutoCodec;
import com.google.devtools.build.skyframe.SkyFunctionName;
import com.google.devtools.build.skyframe.SkyKey;
import com.google.devtools.build.skyframe.SkyValue;
import javax.annotation.Nullable;

/**
 * Whether a module extension generates a repo with a given internal name.
 *
 * <p>This is used to verify the names that an {@link ExtensionRepositoryMapping} resolves
 * structurally without making the evaluation depend on the full set of repos generated by the
 * extension: as long as the extension keeps generating the repo, the value doesn't change when the
 * extension adds or removes other repos.
 */
public sealed interface ExtensionRepoNameValue extends SkyValue {
  ExtensionRepoNameValue EXISTS = new Exists();

  /** The extension generates a repo with the given internal name. */
  @AutoCodec
  record Exists() implements ExtensionRepoNameValue {}

  /**
   * The extension doesn't generate a repo with the given internal name.
   *
   * @param didYouMeanSuffix a (possibly empty) suggestion for similar apparent names visible from
   *     the repos generated by the extension, as returned by {@link
   *     net.starlark.java.spelling.SpellChecker#didYouMean}
   */
  @AutoCodec
  record Missing(String didYouMeanSuffix) implements ExtensionRepoNameValue {
    public Missing {
      checkNotNull(didYouMeanSuffix);
    }
  }

  /**
   * Returns null if the repo exists and the "did you mean" suffix for an error message otherwise,
   * as expected by {@link ExtensionRepositoryMapping.StructuralLookupVerifier#verify}.
   */
  @Nullable
  default String didYouMeanSuffixIfMissing() {
    return switch (this) {
      case Exists() -> null;
      case Missing(String didYouMeanSuffix) -> didYouMeanSuffix;
    };
  }

  static Key key(String repoPrefix, String internalName) {
    return new Key(repoPrefix, internalName);
  }

  /**
   * The {@link SkyKey} for an {@link ExtensionRepoNameValue}.
   *
   * @param repoPrefix the unique name of the extension followed by a {@code +}, see {@link
   *     ExtensionRepositoryMapping#repoPrefix()}
   * @param internalName the internal name of the repo
   */
  @AutoCodec
  record Key(String repoPrefix, String internalName) implements SkyKey {
    public Key {
      checkNotNull(repoPrefix);
      checkNotNull(internalName);
    }

    @Override
    public SkyFunctionName functionName() {
      return SkyFunctions.EXTENSION_REPO_NAME;
    }
  }
}
