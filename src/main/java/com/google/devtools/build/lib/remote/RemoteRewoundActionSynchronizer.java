/**
 * A {@link RewoundActionSynchronizer} implementation for Bazel's remote filesystem, which is backed
 * by actual files on disk and requires synchronization to ensure that action outputs aren't deleted
 * while they are being read.
 */
final class RemoteRewoundActionSynchronizer implements RewoundActionSynchronizer {
  /** A task with a cancellation callback. */
  public interface Cancellable {
    void cancel() throws InterruptedException;
  }

  private final RemoteActionInputFetcher actionInputFetcher;
  private final ConcurrentHashMap<ActionLookupData, Cancellable> outputUploadTasks =
      new ConcurrentHashMap<>();

  // A single coarse lock is used to synchronize rewound actions (writers) and both rewound and
  // non-rewound actions (readers) as long as no rewound action has attempted to prepare for its
  // execution.
  // This ensures high throughput and low memory footprint for the common case of no rewound
  // actions. In this case, there won't be any writers and the performance characteristics of a
  // ReentrantReadWriteLock are comparable to that of an atomic counter. A StampedLock would not be
  // a good fit as its performance regresses with 127 or more concurrent readers.
  // Note that it wouldn't be correct to only start using this lock once an action is rewound,
  // because a non-rewound action consuming its non-lost outputs could have already started
  // executing.
  @Nullable private volatile ReadWriteLock coarseLock = new ReentrantReadWriteLock();

  // A fine-grained lock structure that is switched to when the first rewound action attempts to
  // prepare for its execution. This structure is used to ensure that rewound actions do not
  // delete their outputs while they are being read by other actions, while still allowing
  // rewound actions and non-rewound actions to run concurrently (i.e., not force the equivalent
  // of --jobs=1 for as long as a rewound action is running, as the coarse lock would).
  // A rewound action will acquire a write lock on its lookup data before it prepares for
  // execution, while any action will acquire a read lock on the lookup data of any generating
  // action of its inputs before it starts executing.
  // The values of this cache are weakly referenced to ensure that locks are cleaned up when they
  // are no longer needed.
  @Nullable private volatile LoadingCache<ActionLookupData, ReadWriteLock> fineLocks;

  public RemoteRewoundActionSynchronizer(RemoteActionInputFetcher actionInputFetcher) {
    this.actionInputFetcher = actionInputFetcher;
  }

  /*
  Proof of deadlock freedom:

  The coarse lock cannot cause a deadlock. Readers acquire no fine locks while holding it. The
  writer uses it only to switch to fine locks, then releases it before acquiring any fine lock.

  For the fine locks, we show that a cycle of lock waits would imply a cycle of action dependencies.
  Bazel disallows dependency cycles, so this rules out deadlock.

  1. Define the keys and the wait-for graph.

  Each action has one output key, given by outputKeyFor. For an ordinary action, this is the action's
  own key. For an action generated by an ActionTemplate, it is the template's key. All actions from
  the same template expansion therefore share an output key. An action can acquire a write lock
  only for its output key.

  The graph has one node per active Skyframe action execution thread. We refer to each node by the
  action it is executing or preparing to execute. An edge A -[XY(K)]-> B means:

  * A is waiting to acquire the X lock for key K.
  * B holds the Y lock for the same key K.
  * X and Y are R (read) or W (write).

  There may be several edges between the same pair of actions, one for each relevant lock.

  The output-processing work guarded by enterProcessOutputsAndGetLostArtifacts can be left out.
  While holding read locks, that work does not wait for any action to execute. It therefore cannot
  complete a cycle of waits.

  2. Show that every edge in a deadlock cycle must be RW.

  Suppose there is a deadlock, and choose a directed cycle C in the wait-for graph. Consider any
  edge A -[XY(K)]-> B in C:

  * RR: Fine read-lock acquisition starts with the untimed tryLock. This call can acquire the
    read lock even if a writer is queued ahead of it ("barging"). If another thread holds a read
    lock, no writer can hold the write lock, so tryLock succeeds. Thus RR cannot be a blocking edge.

  * WW or WR: A is waiting for a write lock in enterActionPreparation. At that point, A holds no
    locks. It acquires only this one write lock, and SkyframeActionExecutor has not yet called
    enterActionExecution to acquire read locks. Any previous execution released its locks through
    try-with-resources. Since A holds no locks, no other action can be waiting for a lock held by A.
    So A has no incoming edge and cannot be part of C.

  Only RW remains: each action in C waits to read a key that the next action has locked for writing.
  Every action in C also has an incoming edge. Therefore, every action in C holds the write lock
  for its own output key.

  3. Show that each RW edge in C is also an action dependency.

  Consider an edge A -[RW(K)]-> B. By inputKeysFor, A needs a read lock for K because K guards one
  of its inputs. Since B holds the write lock for K, K is B's output key. There are two cases:

  * K identifies an ordinary action. That action is B, so A consumes an output of B and depends
    on B.

  * K identifies an ActionTemplate. Then B is one of its expanded actions, and A consumes either
    an individual file in a tree artifact declared by the template or the whole tree artifact.

    An individual file can only be consumed by another action from the same expansion. If A were
    such an action, its output key would also be K. Step 2 tells us that A already holds the write
    lock for its output key. But B holds the write lock for K, and two actions cannot hold it at
    once. Thus A cannot be consuming an individual file in this case.

    A must therefore consume the whole tree artifact. This makes A depend on all actions in the
    expansion, including B.

  Thus every edge of C is an action dependency. C would be a dependency cycle, which Bazel disallows.

  Notes:
  * Step 3 relies on lock keys preserving action dependencies. A Striped structure with a fixed
    number of locks would let unrelated actions share a lock. A lock wait would then no longer
    imply an action dependency. Such collisions can cause deadlock with two or more stripes.
  * Each action must acquire at most one write lock. Otherwise, a writer could hold one lock while
    waiting for a second. A reader acquiring those locks in the opposite order could deadlock with
    it. Readers acquire their locks in an arbitrary order.
  * A rewound action skips the read lock for its own output key because it already holds the write
    lock. Reentrancy makes this optional for correctness. It avoids an unnecessary acquisition when
    an expanded action consumes outputs from another action in the same expansion.
  */

  @Override
  public SilentCloseable enterActionPreparation(Action action, boolean wasRewound)
      throws InterruptedException {
    // Skyframe schedules non-rewound actions such that they never run concurrently with actions
    // that consume their outputs.
    if (!wasRewound) {
      return () -> {};
    }
    try (SilentCloseable c =
        Profiler.instance().profile(ProfilerTask.ACTION_LOCK, "action.enterActionPreparation")) {
      return enterActionPreparationForRewinding(action);
    }
  }

  private SilentCloseable enterActionPreparationForRewinding(Action action)
      throws InterruptedException {
    var localCoarseLock = coarseLock;
    if (localCoarseLock != null) {
      // This is the first time a rewound action has attempted to prepare for its execution.
      // Switch to using the fine locks under the protection of the coarse write lock.
      try (SilentCloseable c =
          Profiler.instance().profile(ProfilerTask.ACTION_LOCK, "action.prepareFirstRewinding")) {
        localCoarseLock.writeLock().lockInterruptibly();
      }
      try {
        // Check again under the lock to avoid a race between multiple rewound actions attempting
        // to prepare for execution at the same time.
        if (fineLocks == null) {
          fineLocks =
              Caffeine.newBuilder()
                  .weakValues()
                  // TODO: Investigate the effect of fair locks on build wall time.
                  .build((ActionLookupData unused) -> newFineLock());
          // Must be assigned after fineLocks as lockArtifactsForConsumption relies on a null
          // coarseLock implying a non-null fineLocks.
          coarseLock = null;
        }
      } finally {
        localCoarseLock.writeLock().unlock();
      }
    }

    var writeLock = fineLocks.get(outputKeyFor(action)).writeLock();
    try (SilentCloseable c =
        Profiler.instance()
            .profile(ProfilerTask.ACTION_LOCK, "action.awaitRewoundActionConsumers")) {
      writeLock.lockInterruptibly();
    }
    try (SilentCloseable c =
        Profiler.instance().profile(ProfilerTask.INFO, "action.prepareOutputsForRewinding")) {
      prepareOutputsForRewinding(action);
    } catch (Throwable t) {
      writeLock.unlock();
      throw t;
    }
    return writeLock::unlock;
  }

  /**
   * Cancels all async tasks that operate on the action's outputs and resets any cached data about
   * their prefetching state.
   */
  private void prepareOutputsForRewinding(Action action) throws InterruptedException {
    Cancellable task = outputUploadTasks.remove(actionKeyFor(action));
    if (task != null) {
      task.cancel();
    }
    actionInputFetcher.handleRewoundActionOutputs(action.getOutputs());
  }

  @Override
  public SilentCloseable enterActionExecution(
      Action action, boolean wasRewound, InputMetadataProvider metadataProvider)
      throws InterruptedException {
    try (SilentCloseable c =
        Profiler.instance().profile(ProfilerTask.ACTION_LOCK, "action.enterActionExecution")) {
      return lockArtifactsForConsumption(
          action.getInputs().toList(),
          metadataProvider,
          // A rewound action already holds the write lock on the key guarding its outputs and the
          // extra read lock is unnecessary. Actions generated by an ActionTemplate can consume the
          // outputs of other actions from the same expansion, which are guarded by the same key.
          wasRewound ? outputKeyFor(action) : null);
    }
  }

  /**
   * Guards a call to {@link
   * com.google.devtools.build.lib.remote.RemoteImportantOutputHandler#processOutputsAndGetLostArtifacts}.
   */
  public SilentCloseable enterProcessOutputsAndGetLostArtifacts(
      Iterable<Artifact> importantOutputs, InputMetadataProvider fullMetadataProvider)
      throws InterruptedException {
    try (SilentCloseable c =
        Profiler.instance()
            .profile(ProfilerTask.ACTION_LOCK, "action.enterProcessOutputsAndGetLostArtifacts")) {
      return lockArtifactsForConsumption(
          importantOutputs, fullMetadataProvider, /* writeLockedKey= */ null);
    }
  }

  /**
   * Registers a cancellation callback for an upload of action outputs that may still be running
   * after the action has completed.
   */
  public void registerOutputUploadTask(ActionExecutionMetadata action, Cancellable task) {
    // We don't expect to have multiple output upload tasks for the same action registered at the
    // same time.
    outputUploadTasks.merge(
        actionKeyFor(action),
        task,
        (oldTask, newTask) -> {
          throw new IllegalStateException(
              "Attempted to register multiple output upload tasks for %s: %s and %s"
                  .formatted(action, oldTask, newTask));
        });
  }

  private SilentCloseable lockArtifactsForConsumption(
      Iterable<Artifact> artifacts,
      InputMetadataProvider metadataProvider,
      @Nullable ActionLookupData writeLockedKey)
      throws InterruptedException {
    var localCoarseLock = coarseLock;
    if (localCoarseLock != null) {
      // Common case for builds without any rewound actions: acquire the single lock that is never
      // acquired by a writer.
      localCoarseLock.readLock().lockInterruptibly();
    }
    // Read the fine locks after acquiring the coarse lock to allow the fine locks to be inflated
    // lazily.
    var localFineLocks = fineLocks;
    if (localFineLocks == null) {
      // Continuation of the common case for builds without any rewound actions: the fine locks
      // have not been inflated.
      return localCoarseLock.readLock()::unlock;
    }

    // At this point, there has been at least one rewound action that has inflated the fine locks.
    // We need to switch to it.
    if (localCoarseLock != null) {
      localCoarseLock.readLock().unlock();
    }
    var allReadWriteLocks =
        localFineLocks.getAll(inputKeysFor(artifacts, metadataProvider, writeLockedKey)).values();
    var locksToUnlockBuilder =
        ImmutableList.<Lock>builderWithExpectedSize(allReadWriteLocks.size());
    try {
      for (var readWriteLock : allReadWriteLocks) {
        var readLock = readWriteLock.readLock();
        lockFineReadLockInterruptibly(readLock);
        locksToUnlockBuilder.add(readLock);
      }
    } catch (Throwable e) {
      for (var readLock : locksToUnlockBuilder.build()) {
        readLock.unlock();
      }
      throw e;
    }
    var locksToUnlock = locksToUnlockBuilder.build();
    return () -> locksToUnlock.forEach(Lock::unlock);
  }

  /**
   * Acquires a fine read lock without queuing behind a waiting writer if another reader already
   * holds it.
   *
   * <p>The un-timed {@link ReentrantReadWriteLock.ReadLock#tryLock()} is documented to barge even
   * for a fair lock. This property is required by the RR case in the deadlock proof above. The
   * interrupt check preserves the entry semantics of {@link Lock#lockInterruptibly()} because
   * {@link Lock#tryLock()} itself ignores interruption.
   */
  @VisibleForTesting
  static void lockFineReadLockInterruptibly(Lock readLock) throws InterruptedException {
    if (Thread.interrupted()) {
      throw new InterruptedException();
    }
    if (!readLock.tryLock()) {
      readLock.lockInterruptibly();
    }
  }

  /**
   * Creates a read-write lock that remains reachable while either of its views is in use.
   *
   * <p>The standard {@link ReentrantReadWriteLock} views only retain its internal synchronization
   * state, not the parent lock (see
   * <a href="https://bugs.openjdk.org/browse/JDK-8189598">JDK-8189598</a>). This would allow a weak
   * cache value to be collected and replaced while one of its views is still locked. Guava solves
   * this for {@code Striped} by wrapping both views with a reference to the parent. Here the cached
   * value is itself the read view, and the write view retains it, which achieves the same
   * reachability with only two view objects and no allocation when accessing either view.
   */
  @VisibleForTesting
  static ReadWriteLock newFineLock() {
    return new WeakSafeReentrantReadWriteLock();
  }

  private static final class WeakSafeReentrantReadWriteLock
      extends ReentrantReadWriteLock.ReadLock implements ReadWriteLock {
    private static final long serialVersionUID = 1L;

    private final Lock writeLock;

    private WeakSafeReentrantReadWriteLock() {
      this(new ReentrantReadWriteLock());
    }

    private WeakSafeReentrantReadWriteLock(ReentrantReadWriteLock parent) {
      super(parent);
      writeLock = new WeakSafeWriteLock(parent, this);
    }

    @Override
    public Lock readLock() {
      return this;
    }

    @Override
    public Lock writeLock() {
      return writeLock;
    }
  }

  private static final class WeakSafeWriteLock extends ReentrantReadWriteLock.WriteLock {
    private static final long serialVersionUID = 1L;

    // Keep the weakly cached value alive as long as the write view is reachable.
    @SuppressWarnings("unused")
    private final WeakSafeReentrantReadWriteLock cachedValue;

    private WeakSafeWriteLock(
        ReentrantReadWriteLock lock, WeakSafeReentrantReadWriteLock cachedValue) {
      super(lock);
      this.cachedValue = cachedValue;
    }

    @Override
    public Condition newCondition() {
      // StampedLock views, which this class replaces, do not support conditions. A condition would
      // also need to retain the weakly cached value to preserve the reachability guarantee.
      throw new UnsupportedOperationException();
    }
  }

  private static Iterable<ActionLookupData> inputKeysFor(
      Iterable<Artifact> artifacts,
      InputMetadataProvider metadataProvider,
      @Nullable ActionLookupData writeLockedKey) {
    var allArtifacts =
        Iterables.concat(
            artifacts,
            Iterables.concat(
                Iterables.transform(
                    metadataProvider.getRunfilesTrees(),
                    runfilesTree -> runfilesTree.getArtifacts().toList())));
    var result =
        Iterables.transform(
            Iterables.filter(allArtifacts, artifact -> artifact instanceof DerivedArtifact),
            artifact -> lockKeyFor((DerivedArtifact) artifact));
    if (writeLockedKey == null) {
      return result;
    }
    return Iterables.filter(result, key -> !key.equals(writeLockedKey));
  }

  /** Returns the key that uniquely identifies the given action. */
  private static ActionLookupData actionKeyFor(ActionExecutionMetadata action) {
    return ((DerivedArtifact) action.getPrimaryOutput()).getGeneratingActionKey();
  }

  /**
   * Returns the key of the lock that guards the given artifact, which is the generating action key
   * of the outermost tree artifact containing it, or its own if it isn't contained in one.
   *
   * <p>This is the artifact's own generating action key except for the outputs of an {@link
   * com.google.devtools.build.lib.actions.ActionTemplate} expansion, which are guarded by the key
   * of the template: they are only ever consumed as part of a tree artifact the template declares,
   * either by actions outside the expansion, which depend on that tree artifact, or by other
   * actions of the same expansion, which depend on individual files in it.
   */
  private static ActionLookupData lockKeyFor(DerivedArtifact artifact) {
    var outermost = artifact;
    for (var parent = artifact.getParent(); parent != null; parent = parent.getParent()) {
      outermost = parent;
    }
    return outermost.getGeneratingActionKey();
  }

  /**
   * Returns the key of the lock that guards the outputs of the given action, which is the key its
   * consumers acquire the read lock of.
   */
  private static ActionLookupData outputKeyFor(Action action) {
    return lockKeyFor((DerivedArtifact) action.getPrimaryOutput());
  }
}
