package com.google.devtools.build.lib.skyframe;

import com.google.common.collect.ImmutableSet;
import com.google.devtools.build.lib.cmdline.ExtensionRepositoryMapping;
import com.google.devtools.build.skyframe.SkyFunction.Environment;
import com.google.devtools.build.skyframe.SkyframeLookupResult;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;
import javax.annotation.Nullable;

/**
 * Verifies the repos that {@link ExtensionRepositoryMapping}s resolve structurally during a
 * Skyframe evaluation by requesting the corresponding {@link ExtensionRepoNameValue}s.
 *
 * <p>This makes the evaluation resolve apparent names exactly as if the mappings listed all repos
 * generated by the extensions, while only depending on the existence of the individual repos it
 * references. As a result, it doesn't need to be redone when an extension adds or removes repos it
 * doesn't reference.
 *
 * <p>If the value for a name isn't available yet, the name is resolved structurally for now and
 * {@link Environment#valuesMissing()} becomes true. Callers either restart, after which the value
 * will be available, or keep the result of the evaluation around and later check whether all such
 * {@link #unverifiedKeys()} refer to existing repos via {@link #allExist}, in which case the result
 * is the same as if they had been verified right away.
 *
 * <p>Usage: install via {@link ExtensionRepositoryMapping#installVerifier} for the duration of the
 * part of the evaluation that resolves labels, then call {@link #throwIfInterrupted}.
 */
final class ExtensionRepoNameVerifier
    implements ExtensionRepositoryMapping.StructuralLookupVerifier {
  private final Environment env;
  private final Map<ExtensionRepoNameValue.Key, ExtensionRepoNameValue> values = new HashMap<>();
  private final Set<ExtensionRepoNameValue.Key> unverifiedKeys = new LinkedHashSet<>();
  private boolean interrupted = false;

  ExtensionRepoNameVerifier(Environment env) {
    this.env = env;
  }

  @Override
  @Nullable
  public String verify(String repoPrefix, String internalName) {
    var key = ExtensionRepoNameValue.key(repoPrefix, internalName);
    ExtensionRepoNameValue value = values.get(key);
    if (value == null && !unverifiedKeys.contains(key) && !interrupted) {
      try {
        value = (ExtensionRepoNameValue) env.getValue(key);
      } catch (InterruptedException e) {
        // Can't be propagated through the repo mapping lookup, rethrown by throwIfInterrupted.
        interrupted = true;
      }
      if (value != null) {
        values.put(key, value);
      } else {
        unverifiedKeys.add(key);
      }
    }
    return value == null ? null : value.didYouMeanSuffixIfMissing();
  }

  /**
   * Returns whether any names have been resolved structurally without verification since their
   * values weren't available yet. If true, {@link Environment#valuesMissing()} is true as well.
   */
  boolean hasUnverifiedKeys() {
    return !unverifiedKeys.isEmpty();
  }

  /**
   * Returns the keys of the names that have been resolved structurally without verification since
   * their values weren't available yet.
   */
  ImmutableSet<ExtensionRepoNameValue.Key> unverifiedKeys() {
    return ImmutableSet.copyOf(unverifiedKeys);
  }

  /** Throws an {@link InterruptedException} if the thread was interrupted during verification. */
  void throwIfInterrupted() throws InterruptedException {
    if (interrupted) {
      interrupted = false;
      throw new InterruptedException();
    }
  }

  /**
   * Returns true if all given keys refer to existing repos, false if any of them doesn't and null
   * if values are missing.
   */
  @Nullable
  static Boolean allExist(Environment env, Set<ExtensionRepoNameValue.Key> keys)
      throws InterruptedException {
    if (keys.isEmpty()) {
      return true;
    }
    SkyframeLookupResult result = env.getValuesAndExceptions(keys);
    boolean allExist = true;
    for (var key : keys) {
      var value = (ExtensionRepoNameValue) result.get(key);
      if (value == null) {
        return null;
      }
      if (value.didYouMeanSuffixIfMissing() != null) {
        allExist = false;
      }
    }
    return allExist;
  }
}
